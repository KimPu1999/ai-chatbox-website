"""Private object storage boundary for local development and Cloudflare R2.

The adapter is intentionally synchronous because boto3 is synchronous; callers
that run inside async request/worker code must use ``asyncio.to_thread`` for
network operations. Object keys are generated by the document service and are
never accepted from the browser as filesystem paths.
"""

from __future__ import annotations

from typing import Any

from app.core.config import get_settings


class StorageError(RuntimeError):
    pass


def _r2_client() -> Any:
    settings = get_settings()
    required = {
        "R2_ACCOUNT_ID": settings.r2_account_id,
        "R2_BUCKET_NAME": settings.r2_bucket_name,
        "R2_ACCESS_KEY_ID": settings.r2_access_key_id,
        "R2_SECRET_ACCESS_KEY": settings.r2_secret_access_key,
    }
    if any(not value.strip() for value in required.values()):
        raise StorageError("R2 storage is not configured")
    try:
        import boto3

        return boto3.client(
            "s3",
            endpoint_url=settings.r2_s3_endpoint,
            region_name="auto",
            aws_access_key_id=settings.r2_access_key_id,
            aws_secret_access_key=settings.r2_secret_access_key,
        )
    except ImportError as exc:  # pragma: no cover - dependency is installed in production images
        raise StorageError("R2 storage dependency is not installed") from exc


def put_bytes(key: str, data: bytes, content_type: str) -> None:
    settings = get_settings()
    if settings.document_storage_backend == "local":
        raise StorageError("Use local filesystem storage helper for local objects")
    if settings.document_storage_backend != "r2":
        raise StorageError("Unsupported storage backend")
    _r2_client().put_object(
        Bucket=settings.r2_bucket_name,
        Key=key,
        Body=data,
        ContentType=content_type,
    )


def get_bytes(key: str) -> bytes:
    settings = get_settings()
    if settings.document_storage_backend != "r2":
        raise StorageError("Use local filesystem storage helper for local objects")
    response = _r2_client().get_object(Bucket=settings.r2_bucket_name, Key=key)
    body = response["Body"]
    try:
        return body.read()
    finally:
        body.close()


def delete_object(key: str) -> None:
    settings = get_settings()
    if settings.document_storage_backend != "r2":
        raise StorageError("Use local filesystem storage helper for local objects")
    _r2_client().delete_object(Bucket=settings.r2_bucket_name, Key=key)
